export const DEFAULT_LOCALE: Locale = "en";
export const LOCALE_COOKIE = "verex-locale";

export const LOCALE_LABEL: Record<Locale, string> = { en: "EN", ko: "한국어" };

export function isLocale(v: unknown): v is Locale {
  return v === "en" || v === "ko";
}

